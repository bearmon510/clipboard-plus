enum ClipboardPrivacy {
    static func hasPrivateMarker(in types: [String]) -> Bool {
        types.contains {
            $0 == "org.nspasteboard.ConcealedType"
                || $0 == "org.nspasteboard.TransientType"
                || $0 == "org.nspasteboard.AutoGeneratedType"
        }
    }
}
