import Foundation
import UIKit
import UniformTypeIdentifiers

@MainActor
protocol KeyboardPasteboardReadable: AnyObject {
    var types: [String] { get }
    var hasStrings: Bool { get }
    var hasURLs: Bool { get }
    var string: String? { get }
    var url: URL? { get }
}

extension UIPasteboard: KeyboardPasteboardReadable {}

enum SharedTextExtractor {
    static let acceptedTypeIdentifiers: [String] = [
        UTType.url.identifier,
        UTType.utf8PlainText.identifier,
        UTType.plainText.identifier,
        UTType.text.identifier,
    ]

    private static let privateTypeMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    enum PasteboardReadResult: Equatable {
        case text(String)
        case concealed
        case emptyOrUnsupported
    }

    static func hasPrivateMarker(in types: [String]) -> Bool {
        types.contains { privateTypeMarkers.contains($0) }
    }

    static func hasPrivateMarker(in providers: [NSItemProvider]) -> Bool {
        providers.contains { hasPrivateMarker(in: $0.registeredTypeIdentifiers) }
    }

    static func canAccept(_ providers: [NSItemProvider]) -> Bool {
        guard !hasPrivateMarker(in: providers) else { return false }
        return providers.contains(where: isAcceptableProvider)
    }

    private static func isAcceptableProvider(_ provider: NSItemProvider) -> Bool {
        if provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier),
           !provider.hasItemConformingToTypeIdentifier(UTType.plainText.identifier) {
            return false
        }
        return provider.hasItemConformingToTypeIdentifier(UTType.url.identifier)
            || provider.hasItemConformingToTypeIdentifier(UTType.plainText.identifier)
            || provider.canLoadObject(ofClass: NSString.self)
    }

    static func isAcceptedWebURL(_ url: URL) -> Bool {
        guard !url.isFileURL,
              let scheme = url.scheme?.lowercased(),
              scheme == "http" || scheme == "https",
              let host = url.host,
              !host.isEmpty else {
            return false
        }
        return true
    }

    static func normalizedCandidate(_ text: String?) -> String? {
        guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return nil
        }
        return text
    }

    @MainActor
    static func extractFromPasteboard(_ pasteboard: KeyboardPasteboardReadable) -> PasteboardReadResult {
        let types = pasteboard.types
        if hasPrivateMarker(in: types) {
            return .concealed
        }
        if types.contains(UTType.fileURL.identifier),
           !types.contains(UTType.plainText.identifier),
           !types.contains(UTType.utf8PlainText.identifier) {
            return .emptyOrUnsupported
        }
        if pasteboard.hasStrings, let string = normalizedCandidate(pasteboard.string) {
            if let url = URL(string: string.trimmingCharacters(in: .whitespacesAndNewlines)), url.isFileURL {
                return .emptyOrUnsupported
            }
            return .text(string)
        }
        if pasteboard.hasURLs, let url = pasteboard.url, isAcceptedWebURL(url) {
            return .text(url.absoluteString)
        }
        return .emptyOrUnsupported
    }

    static func extractTexts(from items: [NSExtensionItem]) async -> [String] {
        let providers = items.flatMap { $0.attachments ?? [] }
        return await extractTexts(from: providers)
    }

    static func extractTexts(from providers: [NSItemProvider]) async -> [String] {
        var collected: [String] = []
        var seen: Set<String> = []
        for provider in providers {
            if Task.isCancelled { break }
            guard let text = await extractText(from: provider) else { continue }
            if seen.insert(text).inserted {
                collected.append(text)
            }
        }
        return collected
    }

    static func extractFirstText(from providers: [NSItemProvider]) async -> String? {
        guard !hasPrivateMarker(in: providers) else { return nil }
        for provider in providers {
            if Task.isCancelled { return nil }
            if let text = await extractText(from: provider) {
                return text
            }
        }
        return nil
    }

    static func extractText(from provider: NSItemProvider) async -> String? {
        if hasPrivateMarker(in: provider.registeredTypeIdentifiers) {
            return nil
        }
        if provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier),
           !provider.hasItemConformingToTypeIdentifier(UTType.plainText.identifier) {
            return nil
        }
        if provider.hasItemConformingToTypeIdentifier(UTType.url.identifier),
           !provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier),
           let urlText = await loadURLString(from: provider) {
            return urlText
        }
        if provider.hasItemConformingToTypeIdentifier(UTType.plainText.identifier)
            || provider.canLoadObject(ofClass: NSString.self) {
            return await loadPlainText(from: provider)
        }
        return nil
    }

    private static func loadURLString(from provider: NSItemProvider) async -> String? {
        await withCheckedContinuation { continuation in
            provider.loadItem(forTypeIdentifier: UTType.url.identifier, options: nil) { item, _ in
                if let url = item as? URL {
                    continuation.resume(returning: isAcceptedWebURL(url) ? url.absoluteString : nil)
                } else if let data = item as? Data,
                          let url = URL(dataRepresentation: data, relativeTo: nil) {
                    continuation.resume(returning: isAcceptedWebURL(url) ? url.absoluteString : nil)
                } else if let text = item as? String,
                          let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)),
                          isAcceptedWebURL(url) {
                    continuation.resume(returning: url.absoluteString)
                } else {
                    continuation.resume(returning: nil)
                }
            }
        }
    }

    private static func loadPlainText(from provider: NSItemProvider) async -> String? {
        if provider.canLoadObject(ofClass: NSString.self) {
            let objectText: String? = await withCheckedContinuation { continuation in
                provider.loadObject(ofClass: NSString.self) { object, _ in
                    continuation.resume(returning: object as? String)
                }
            }
            if let objectText = normalizedCandidate(objectText) {
                return objectText
            }
        }
        let identifier = provider.hasItemConformingToTypeIdentifier(UTType.utf8PlainText.identifier)
            ? UTType.utf8PlainText.identifier
            : UTType.plainText.identifier
        guard provider.hasItemConformingToTypeIdentifier(identifier) else { return nil }
        return await withCheckedContinuation { continuation in
            provider.loadItem(forTypeIdentifier: identifier, options: nil) { item, _ in
                if let text = item as? String {
                    continuation.resume(returning: normalizedCandidate(text))
                } else if let attributed = item as? NSAttributedString {
                    continuation.resume(returning: normalizedCandidate(attributed.string))
                } else if let data = item as? Data {
                    continuation.resume(returning: normalizedCandidate(String(data: data, encoding: .utf8)))
                } else {
                    continuation.resume(returning: nil)
                }
            }
        }
    }
}

enum ShareSaveOutcome: Equatable {
    case saved(count: Int)
    case noSupportedContent
    case storageUnavailable
    case saveFailed

    var title: String {
        switch self {
        case .saved:
            return "clipboard+ に保存しました"
        case .noSupportedContent:
            return "保存できる文章やリンクがありません"
        case .storageUnavailable, .saveFailed:
            return "clipboard+ に保存できませんでした"
        }
    }

    var subtitle: String? {
        switch self {
        case .saved(let count):
            return count > 1 ? "\(count)件を保存しました。アプリを開くと履歴に入ります。" : nil
        case .noSupportedContent:
            return "現在は文章とWebのリンクのみ保存できます"
        case .storageUnavailable:
            return "共有コンテナを開けませんでした"
        case .saveFailed:
            return "書き込みに失敗しました"
        }
    }

    var symbolName: String {
        switch self {
        case .saved:
            return "checkmark.circle.fill"
        case .noSupportedContent:
            return "doc.text"
        case .storageUnavailable, .saveFailed:
            return "exclamationmark.triangle.fill"
        }
    }

    var autoDismissDelayNanoseconds: UInt64 {
        switch self {
        case .saved:
            return 1_000_000_000
        case .noSupportedContent, .storageUnavailable, .saveFailed:
            return 1_500_000_000
        }
    }

    static func save(
        texts: [String],
        inboxDirectory: URL?,
        write: (String, URL) throws -> Void = { text, directory in
            _ = try SharedInbox.write(text: text, origin: .shareExtension, to: directory)
        }
    ) -> ShareSaveOutcome {
        guard !texts.isEmpty else { return .noSupportedContent }
        guard let directory = inboxDirectory else { return .storageUnavailable }
        var savedCount = 0
        for text in texts {
            if (try? write(text, directory)) != nil {
                savedCount += 1
            }
        }
        return savedCount > 0 ? .saved(count: savedCount) : .saveFailed
    }
}
