import XCTest
@testable import ClipboardPlus

final class ClipboardPrivacyTests: XCTestCase {
    func testEachPrivateMarkerIsRecognizedAmongOtherTypes() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertTrue(ClipboardPrivacy.hasPrivateMarker(in: [marker]))
            XCTAssertTrue(ClipboardPrivacy.hasPrivateMarker(in: ["public.png", marker, "public.utf8-plain-text"]))
        }
    }

    func testOrdinaryAndEmptyTypesAreNotPrivate() {
        XCTAssertFalse(ClipboardPrivacy.hasPrivateMarker(in: []))
        XCTAssertFalse(ClipboardPrivacy.hasPrivateMarker(in: ["public.utf8-plain-text", "public.url", "public.png"]))
        XCTAssertFalse(ClipboardPrivacy.hasPrivateMarker(in: ["org.nspasteboard.ConcealedType.extra"]))
    }
}
